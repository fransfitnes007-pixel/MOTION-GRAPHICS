#!/usr/bin/env python3
"""Rebuilds the library's front door from the skill folders: catalog.json, INDEX.md and LIBRARY.html.
Run after adding or changing pieces:  python3 engine/tools/build_index.py"""
import html, json, os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', 'library'))
CATS = [('motion-graphics', 'Motion graphics'), ('ui-components', 'UI components'), ('dashboards', 'Dashboards'), ('sound', 'Sound')]

items = []
for cat, _ in CATS:
    d = os.path.join(ROOT, cat)
    if not os.path.isdir(d): continue
    for slug in sorted(os.listdir(d)):
        p = os.path.join(d, slug)
        mp = os.path.join(p, 'meta.json')
        if not os.path.isfile(mp): continue
        m = json.load(open(mp))
        med = os.path.join(p, 'media')
        files = sorted(os.listdir(med)) if os.path.isdir(med) else []
        clips = [f for f in files if f.startswith('clip-') and f.endswith('.mp4')]
        sound = next((f for f in files if f.startswith('sound.')), None)
        rel = f'{cat}/{slug}'
        items.append({
            'slug': slug, 'path': rel, 'category': cat,
            'visual_name': m.get('visual_name', slug), 'code_name': m.get('code_name', ''),
            'summary': m.get('summary', ''), 'aliases': m.get('aliases', []), 'tags': m.get('tags', []), 'tech': m.get('tech', []),
            'duration_sec': m.get('duration_sec'), 'demo_kind': m.get('demo_kind', ''),
            'projects': [],
            'clips': [f'{rel}/media/{c}' for c in clips],
            'clip': f'{rel}/media/{next((c for c in clips if "wide" in c), clips[0])}' if clips else None,
            'poster': f'{rel}/media/poster.jpg' if 'poster.jpg' in files else None,
            'sound': f'{rel}/media/{sound}' if sound else None,
            'demo': f'{rel}/code/demo.html' if os.path.isfile(os.path.join(p, 'code', 'demo.html')) else None,
            'skill': f'{rel}/SKILL.md',
        })

json.dump({'count': len(items), 'skills': items}, open(os.path.join(ROOT, 'catalog.json'), 'w'), indent=1)

# ---------- INDEX.md: greppable by you and by Claude
lines = ['# Skill index', '', f'{len(items)} skills. Generated by `engine/tools/build_index.py`; do not edit by hand. For the visual version, open `LIBRARY.html`.', '']
for cat, title in CATS:
    rows = [i for i in items if i['category'] == cat]
    if not rows: continue
    lines += [f'## {title} ({len(rows)})', '', '| Visual | Code | What you see |', '|---|---|---|']
    for i in rows:
        s = i['summary'].replace('|', '/').replace('\n', ' ')
        path = i['path'].replace(' ', '%20')
        lines.append(f"| [{i['visual_name']}]({path}/SKILL.md) | {i['code_name']} | {s} |")
    lines.append('')
open(os.path.join(ROOT, 'INDEX.md'), 'w').write('\n'.join(lines))

