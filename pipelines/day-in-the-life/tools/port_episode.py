#!/usr/bin/env python3
"""Copy one finished Day in the Life episode from a private build library into this kit's public library, white-labelled.

  python3 pipelines/day-in-the-life/tools/port_episode.py <episode-folder> --part N [--brand "RealName"] [--no-poster]

<episode-folder> is a build folder made with this pipeline (SKILL.md, meta.json, code/demo.src.html or code/demo.html,
code/_shared_ui.js, code/recipe.py, code/three.min.js). The copy lands in library/motion-graphics/<slug>/ with:
  - your real brand words swapped for the YourBrand placeholders (so engine/tools/apply_brand.py keeps working),
    platform names made generic, voice names reduced to "voice A" / "voice B", app source paths removed;
  - the font switched to the system stack (licensed font files are never copied);
  - brand-assets.js replaced by the kit's generated one (chrome monogram and wordmark from brand.config.json);
  - no voice audio, no mixed sound, no clips (they speak or show the real brand): only code, SKILL.md, meta.json
    and a fresh poster rendered from the white-labelled demo.
Put your real brand words in the private words file (see port-words.example.json) or pass --brand.
Then run: node engine/tools/verify_library.cjs <slug> and python3 engine/tools/build_index.py."""
import argparse, glob, json, os, re, shutil, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
FONT = 'system-ui, -apple-system, BlinkMacSystemFont, Helvetica, Arial, sans-serif'

# Words to swap. The private list (your real brand, its asset names, platform names, voice names, people, internal
# paths) lives in a JSON file kept out of git: --words <file> (default ../reference/port-words.json, and reference/ is
# git-ignored). Format: see port-words.example.json next to this script. Rules run in order, private ones first.
GENERIC = [
    (r'`?(?:[\w-]+/)+[\w.-]+\.tsx?`?', 'the app'),                   # source paths of the private app
    (r'_engine/tools', 'engine/tools'), (r'chrome G\b', 'chrome monogram'), (r'\bG mark\b', 'monogram'),
]
PRIVATE, DROP = [], None
DROP_LINE = re.compile(r'~/|/Users/|\*\*Claims:\*\*')


def load_words(path):
    global PRIVATE, DROP
    if path and os.path.exists(path):
        j = json.load(open(path)); PRIVATE = [tuple(x) for x in j.get('replace', [])]
        DROP = re.compile(j['drop_line']) if j.get('drop_line') else None


def wl(s, extra=()):
    for a, b in list(extra) + PRIVATE + GENERIC:
        s = re.sub(a, b, s)
    return s


def code(s, extra=()):
    s = re.sub(r"@font-face\{font-family:'SFD'[^}]*\}\n?", '', s)
    s = re.sub(r"await document\.fonts\.load\('[^']*SFD'\);?\s*", '', s)
    s = re.sub(r'\bSFD\b', FONT, s)
    return wl(s, extra)


def skill(md, part, slug, dur):
    out, section = [], None
    fm = md.split('---', 2)
    body = fm[2] if len(fm) == 3 else md
    desc = re.search(r'^description:\s*(.*)$', fm[1], re.M).group(1) if len(fm) == 3 else ''
    for ln in body.split('\n'):
        if ln.startswith('## '):
            section = ln[3:].strip()
            if section == 'Files':
                continue
        if section == 'Files':
            continue
        if ln.startswith('**Code name:**'):
            ln = re.split(r'\s*\*\*From:\*\*', ln)[0] + f' **From:** original build, part {part} of the Day in the Life series (`pipelines/day-in-the-life/`).'
        if re.match(r'Watch `media/clip-tall\.mp4`', ln):
            ln = f'Render it: `node engine/tools/render_demo.cjs video library/motion-graphics/{slug}/code/demo.html out.mp4 1080 1920` (about {dur} seconds, 1080x1920; no voice is included, see `pipelines/day-in-the-life/PLAYBOOK.md`).'
        if DROP_LINE.search(ln) or (DROP and DROP.search(ln)):
            continue
        out.append(ln)
    text = '\n'.join(out).strip() + '\n'
    text = re.sub(r'\n{3,}', '\n\n', text)
    files = (f'\n## Files\n`code/demo.html` (runnable), `code/demo.src.html` + `code/_shared_ui.js` (the build sources: '
             '`/*SHARED_UI*/` in the src is replaced by the shared file), `code/recipe.py` (synthesised sound effects on the beat '
             'times; drop your own voice take next to it as `voiceover.wav`), `code/three.min.js` (three.js, MIT), '
             '`code/brand-assets.js` (generated by `engine/tools/apply_brand.py`), `media/poster.jpg`. Voice audio, the mixed '
             'sound and the rendered clip are not published.\n')
    name = slug.replace('__', '-')
    return f'---\nname: {name}\ndescription: {wl(desc)}\n---\n\n' + wl(text) + files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('src'); ap.add_argument('--part', type=int, required=True)
    ap.add_argument('--brand', action='append', default=[], help='extra real brand word to replace with YourBrand')
    ap.add_argument('--no-poster', action='store_true'); ap.add_argument('--poster-t', type=float)
    ap.add_argument('--words', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'reference', 'port-words.json'))
    a = ap.parse_args()
    load_words(a.words)
    extra = [(re.escape(b), 'YourBrand') for b in a.brand]
    src = os.path.abspath(a.src.rstrip('/'))
    slug = wl(os.path.basename(src), extra).lower().replace('yourbrand', 'brand')
    dst = os.path.join(ROOT, 'library', 'motion-graphics', slug)
    if os.path.exists(dst):
        shutil.rmtree(dst)
    os.makedirs(os.path.join(dst, 'code')); os.makedirs(os.path.join(dst, 'media'))
    c = os.path.join(src, 'code')
    rd = lambda p: open(p, encoding='utf-8').read()
    wr = lambda p, s: open(os.path.join(dst, p), 'w', encoding='utf-8').write(s)
    if os.path.exists(os.path.join(c, 'demo.src.html')):
        s = code(rd(os.path.join(c, 'demo.src.html')), extra); ui = code(rd(os.path.join(c, '_shared_ui.js')), extra)
        wr('code/demo.src.html', s); wr('code/_shared_ui.js', ui); wr('code/demo.html', s.replace('/*SHARED_UI*/', ui))
    else:
        wr('code/demo.html', code(rd(os.path.join(c, 'demo.html')), extra))
    rec = wl(rd(os.path.join(c, 'recipe.py')), extra)
    rec = re.sub(r"vo, sr = sf\.read\(os\.path\.join\(here, 'voiceover\.wav'\)\); assert sr == SR",
                 "vp = os.path.join(here, 'voiceover.wav')  # your own take, 48 kHz; effects only without it\n"
                 "vo, sr = sf.read(vp) if os.path.exists(vp) else (np.zeros(SR), SR); assert sr == SR", rec)
    rec = rec.replace('/ np.abs(vo).max()', '/ max(np.abs(vo).max(), 1e-9)')
    wr('code/recipe.py', rec)
    shutil.copy(os.path.join(c, 'three.min.js'), os.path.join(dst, 'code', 'three.min.js'))
    ba = sorted(glob.glob(os.path.join(ROOT, 'library', '*', '*', 'code', 'brand-assets.js')))
    ba = [p for p in ba if not p.startswith(dst)]
    shutil.copy(ba[0], os.path.join(dst, 'code', 'brand-assets.js'))
    m = json.load(open(os.path.join(src, 'meta.json')))
    html = rd(os.path.join(dst, 'code', 'demo.html'))
    T = {k: float(v) for k, v in re.findall(r'(\w+):\s*(-?[\d.]+)', re.search(r'const T = (\{.*?\})', html, re.S).group(1))}
    dur = m.get('duration_sec') or T.get('dur')
    wr('SKILL.md', skill(rd(os.path.join(src, 'SKILL.md')), a.part, slug, dur))
    lst = lambda xs: [wl(x, extra) for x in xs or []]
    meta = {
        'slug': slug, 'visual_name': wl(m['visual_name'], extra), 'code_name': wl(m['code_name'], extra), 'category': 'motion-graphics',
        'summary': wl(m['summary'], extra), 'aliases': lst(m.get('aliases')),
        'tags': sorted(set(['brand' if t == 'yourbrand' else t for t in lst(m.get('tags'))] + ['day-in-the-life'])),
        'tech': lst(m.get('tech')), 'duration_sec': dur, 'has_sound': False, 'demo_kind': 'original-build',
        'series': 'day-in-the-life', 'part': a.part,
        'credit': 'Original code, this repository (MIT). three.js (MIT, three.js authors) bundled as code/three.min.js.',
        'variants_elsewhere': [wl(v, extra).replace('yourbrand', 'brand') for v in m.get('variants_elsewhere') or []],
    }
    json.dump(meta, open(os.path.join(dst, 'meta.json'), 'w'), indent=2, ensure_ascii=False)
    if not a.no_poster:
        t = a.poster_t
        if t is None:
            f = T.get('foundG') or T.get('found'); end = T.get('end') or dur - 5
            t = round(min((f + 2.6) if f else end * 0.6, end - 1), 2)
        tmp = os.path.join(dst, 'media', '_p')
        subprocess.run(['node', os.path.join(ROOT, 'engine/tools/render_demo.cjs'), 'still', os.path.join(dst, 'code/demo.html'), tmp, str(t), '1080', '1920'], check=True, cwd=ROOT, capture_output=True)
        from PIL import Image
        Image.open(glob.glob(tmp + '/*.png')[0]).convert('RGB').resize((540, 960), Image.LANCZOS).save(os.path.join(dst, 'media', 'poster.jpg'), quality=86)
        shutil.rmtree(tmp)
    print(slug)


if __name__ == '__main__':
    main()
